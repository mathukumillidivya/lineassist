"""Generate what the live demo needs from the pinned benchmark checkout.

Run inside the benchmark's environment:
    cd tau2-bench && PYTHONPATH=.. uv run python ../scripts/build_live.py

Writes
  app/site/sim.json            simulator sources (benchmark files + small stand-ins), databases, scenarios
  app/netlify/lib/prompt.mjs   system prompts and tool definitions used by the server function
"""
import json
import tomllib
from pathlib import Path

from tau2.domains.telecom.environment import get_environment, get_tasks
from tau2.domains.telecom.utils import TELECOM_DB_PATH, TELECOM_USER_DB_PATH

from lineassist.agent import INSTRUCTION, REVIEW_SYSTEM, SYSTEM_WITH_PLAYBOOK
from lineassist.playbook import PLAYBOOK

from build_demo import CHECKS, FAULTS

ROOT = Path(__file__).resolve().parent.parent
DOMAIN = Path(TELECOM_DB_PATH).parent
SRC = Path(__import__("tau2").__file__).parent / "domains" / "telecom"

# title, what the visitor is told, task id
SCENARIOS = [
    ("Abroad with no data", "A gentle start: two things are wrong.",
     "[mobile_data_issue]airplane_mode_on|user_abroad_roaming_enabled_off[PERSONA:None]"),
    ("Slow data in France", "Four faults, two of them on the account.",
     "[mobile_data_issue]bad_network_preference|bad_vpn|data_usage_exceeded|user_abroad_roaming_disabled_on[PERSONA:None]"),
    ("Photos will not send", "Picture messages fail for several unrelated reasons.",
     "[mms_issue]bad_wifi_calling|break_apn_mms_setting|break_app_sms_permission|data_mode_off[PERSONA:None]"),
    ("No service at all", "The phone and the account both have a problem.",
     "[service_issue]airplane_mode_on|overdue_bill_suspension|unseat_sim_card[PERSONA:None]"),
    ("The line the agent must not reactivate", "The right outcome here is a transfer to a human. Try to talk it out of that.",
     "[service_issue]airplane_mode_on|contract_end_suspension[PERSONA:None]"),
    ("Everything at once", "Seven or more faults. The standard agent solved none of these.", None),
]


def main() -> None:
    tasks = {t.id: t for t in get_tasks("full")}
    names = lambda tid: tid.split("]")[1].split("[")[0].split("|")
    scenarios = []
    for title, blurb, tid in SCENARIOS:
        if tid is None:
            tid = next(t for t in sorted(tasks) if t.startswith("[mms_issue]") and t.endswith("[PERSONA:None]") and len(names(t)) == 8)
        if tid not in tasks:
            want = set(names(tid))
            tid = next(t for t in sorted(tasks) if t.split("]")[0] == tid.split("]")[0] and set(names(t)) == want)
        t = tasks[tid]
        ins = t.user_scenario.instructions
        crit = t.evaluation_criteria
        scenarios.append({
            "title": title, "blurb": blurb, "task_id": tid, "faults": [FAULTS[f] for f in names(tid)],
            "check_labels": {a.func_name: CHECKS.get(a.func_name, a.func_name) for a in (crit.env_assertions or [])},
            "reason": ins.reason_for_call, "known": ins.known_info,
            "init": [a.model_dump() for a in (t.initial_state.initialization_actions or [])],
            "assertions": [a.model_dump() for a in (crit.env_assertions or [])],
            "transfer_expected": any(a.name == "transfer_to_human_agents" for a in (crit.actions or [])),
        })
        print(f"{title}: {tid}")

    py = {}
    for f in ("data_model.py", "user_data_model.py", "tools.py", "user_tools.py"):
        py[f"tau2/domains/telecom/{f}"] = (SRC / f).read_text()          # benchmark files, unmodified
    stubs = ROOT / "app/sim/stubs"
    for f in sorted(stubs.rglob("*.py")):
        py[str(f.relative_to(stubs))] = f.read_text()
    py["sim.py"] = (ROOT / "app/sim/sim.py").read_text()
    bundle = {"py": py, "db": tomllib.loads(Path(TELECOM_DB_PATH).read_text()),
              "user_db": tomllib.loads(Path(TELECOM_USER_DB_PATH).read_text()), "scenarios": scenarios}
    out = ROOT / "app/site/sim.json"
    out.write_text(json.dumps(bundle, default=str))
    print(f"{out}: {out.stat().st_size / 1e3:.0f} kB")

    env = get_environment()
    tools = []
    for tool in env.get_tools():
        fn = tool.openai_schema["function"]
        tools.append({"name": fn["name"], "description": fn.get("description", ""), "input_schema": fn["parameters"]})
    system = SYSTEM_WITH_PLAYBOOK.format(instruction=INSTRUCTION, policy=env.get_policy(), playbook=PLAYBOOK)
    lib = ROOT / "app/netlify/lib/prompt.mjs"
    lib.write_text("// Generated by scripts/build_live.py. Do not edit by hand.\n"
                   f"export const SYSTEM = {json.dumps(system)};\n"
                   f"export const REVIEW_SYSTEM = {json.dumps(REVIEW_SYSTEM.format(playbook=PLAYBOOK))};\n"
                   f"export const TOOLS = {json.dumps(tools)};\n")
    print(f"{lib}: {lib.stat().st_size / 1e3:.0f} kB, {len(tools)} tools")


if __name__ == "__main__":
    main()
